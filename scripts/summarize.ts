// Writes the dashboard summary for one area: docs/summaries/<area>.json (+ docs/badges/<area>.svg),
// then rebuilds docs/summaries.js, which Main.dc.html loads as window.SUMMARIES.
// Usage: bun scripts/summarize.ts adr   (normally via `make`, which only runs it when the source changed)
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

type Segment = { label: string; n: number; color: string };
export type Summary = { status: string; tone: 'ok' | 'warn' | 'alert' | 'neutral'; metric: string; metricLabel: string; segments: Segment[] };

const DARK = '#1F2633', MID = '#6E86E8', LIGHT = '#D5DAE1', ALERT = '#C2410C';

// ponytail: reads only `key: value` front-matter blocks; switch to the adr package's parser if it ever exports one.
const frontMatter = (md: string) =>
  [...md.matchAll(/^---\n((?:[\w-]+:.*\n)+)---$/gm)].map((m) =>
    Object.fromEntries(m[1].trim().split('\n').map((l) => [l.slice(0, l.indexOf(':')).trim().toLowerCase(), l.slice(l.indexOf(':') + 1).trim()])));

const STATUSES = ['accepted', 'proposed', 'superseded', 'deprecated', 'rejected'];

export const adrCounts = (md: string, today: string) => {
  const recs = frontMatter(md);
  const count = (s: string) => recs.filter((r) => (STATUSES.includes(r.status?.toLowerCase()) ? r.status.toLowerCase() : 'proposed') === s).length;
  const soon = new Date(Date.parse(today) + 30 * 864e5).toISOString().slice(0, 10);
  // Revisit due = overdue or within 30 days, as in the ADR viewer.
  const due = recs.filter((r) => /^\d{4}-\d{2}-\d{2}$/.test(r.revisit ?? '') && r.revisit <= soon).length;
  return { total: recs.length, due, ...Object.fromEntries(STATUSES.map((s) => [s, count(s)])) } as Record<string, number>;
};

const adrSummary = (c: Record<string, number>): Summary => ({
  ...(c.due ? { status: `${c.due} revisit due`, tone: 'alert' as const }
    : c.proposed ? { status: `${c.proposed} proposed`, tone: 'neutral' as const }
    : { status: 'Up to date', tone: 'ok' as const }),
  metric: String(c.total),
  metricLabel: 'decision records',
  segments: [
    { label: 'Accepted', n: c.accepted, color: DARK },
    { label: 'Proposed', n: c.proposed, color: MID },
    { label: 'Superseded', n: c.superseded + c.deprecated + c.rejected, color: LIGHT },
    { label: 'Revisit due', n: c.due, color: ALERT }
  ].filter((s) => s.n > 0)
});

// Shields-style badge, as the ADR viewer makes: ( A: 3 ✅ | P: 2 ⏳ | D: 1 ⚠️ )
export const adrBadge = (c: Record<string, number>) => {
  const parts = [[`A: ${c.accepted} ✅`, '#17603F'], [`P: ${c.proposed} ⏳`, '#2F5BEA'], [`D: ${c.due} ⚠️`, ALERT]];
  let x = 0;
  const segs = parts.map(([t, bg]) => {
    const w = [...t].reduce((w, ch) => w + (/\p{Extended_Pictographic}/u.test(ch) ? 14 : ch === '️' ? 0 : 7), 12);
    const s = `<rect x="${x}" width="${w}" height="20" fill="${bg}"/><text x="${x + w / 2}" y="14" fill="#fff">${t}</text>`;
    x += w;
    return s;
  });
  const title = `Decisions: ${c.accepted} accepted, ${c.proposed} proposed, ${c.due} due for revisit`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${x}" height="20" role="img" aria-label="${title}"><title>${title}</title>`
    + `<clipPath id="r"><rect width="${x}" height="20" rx="7"/></clipPath>`
    + `<g clip-path="url(#r)" font-family="Verdana,DejaVu Sans,sans-serif" font-size="11" text-anchor="middle">${segs.join('')}</g></svg>\n`;
};

// One entry per area with a real source. Add goals, risks, … here as their files arrive.
const AREAS: Record<string, (today: string) => { summary: Summary; badge?: string }> = {
  adr: (today) => {
    const c = adrCounts(readFileSync('docs/adr/decisions.md', 'utf8'), today);
    return { summary: adrSummary(c), badge: adrBadge(c) };
  }
};

if (import.meta.main) {
  const area = process.argv[2];
  if (!AREAS[area]) throw new Error(`unknown area "${area}"; known: ${Object.keys(AREAS).join(', ')}`);
  const { summary, badge } = AREAS[area](new Date().toISOString().slice(0, 10));
  mkdirSync('docs/summaries', { recursive: true });
  writeFileSync(`docs/summaries/${area}.json`, JSON.stringify(summary, null, 2) + '\n');
  if (badge) {
    mkdirSync('docs/badges', { recursive: true });
    writeFileSync(`docs/badges/${area}.svg`, badge);
  }
  const all = Object.fromEntries(readdirSync('docs/summaries').filter((f) => f.endsWith('.json'))
    .map((f) => [f.slice(0, -5), JSON.parse(readFileSync(`docs/summaries/${f}`, 'utf8'))]));
  writeFileSync('docs/summaries.js', `// Generated by scripts/summarize.ts — do not edit.\nwindow.SUMMARIES = ${JSON.stringify(all, null, 2)};\n`);
  console.log(`summarized ${area}: ${summary.metric} ${summary.metricLabel}, ${summary.status}`);
}
