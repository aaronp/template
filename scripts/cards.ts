// Bundles every docs/**/card.json into docs/cards.js (window.CARDS, keyed by path) for Main.dc.html,
// which reads it with a plain <script> so the dashboard also works from file://.
import { Glob } from 'bun';

const paths = (await Array.fromAsync(new Glob('docs/**/card.json').scan('.'))).sort();
const cards = Object.fromEntries(await Promise.all(paths.map(async (p) => [p, await Bun.file(p).json()])));
await Bun.write('docs/cards.js', `// Generated by scripts/cards.ts (make snapshot). Do not edit.\nwindow.CARDS = ${JSON.stringify(cards, null, 2)};\n`);
console.log(`Wrote docs/cards.js (${paths.join(', ') || 'no cards'})`);
